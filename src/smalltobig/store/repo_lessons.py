"""Lessons live only as YAML in settings.lessons_dir — no SQLite table.

Unlike Source/Claim/Rule/Conflict, a Lesson has no accept/reject/resolve
workflow to track (docs/PLAN.md §2 Stage 4: "generated by the model...
then hand-edited" directly). A parallel DB row would just be a second
copy of the same data that could drift from a hand-edit — so the YAML
files on disk are the only copy, and the web UI reads them directly.
That also means a hand-edit to a lesson file is picked up immediately,
with no sync step, genuinely delivering "editable without the app
running" rather than approximating it.
"""

from __future__ import annotations

from datetime import UTC, datetime
from typing import TYPE_CHECKING

import yaml

from smalltobig.models.lesson import Lesson

if TYPE_CHECKING:
    from pathlib import Path

    from smalltobig.config import Settings


def lesson_yaml_path(settings: Settings, lesson_id: str) -> Path:
    return settings.lessons_dir / f"{lesson_id}.yaml"


def create(settings: Settings, lesson: Lesson) -> None:
    data = {
        "id": lesson.id,
        "name": lesson.name,
        "rule_ids": lesson.rule_ids,
        "scenario_id": lesson.scenario_id,
    }
    path = lesson_yaml_path(settings, lesson.id)
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(yaml.safe_dump(data, sort_keys=False), encoding="utf-8")


def get(settings: Settings, lesson_id: str) -> Lesson | None:
    path = lesson_yaml_path(settings, lesson_id)
    if not path.is_file():
        return None
    return _load(path)


def list_all(settings: Settings) -> list[Lesson]:
    if not settings.lessons_dir.is_dir():
        return []
    lessons = [_load(path) for path in sorted(settings.lessons_dir.glob("*.yaml"))]
    return sorted(lessons, key=lambda lesson: lesson.id)


def _load(path: Path) -> Lesson:
    data = yaml.safe_load(path.read_text(encoding="utf-8"))
    # created_at isn't part of the on-disk schema (a human editing the
    # file shouldn't have to know or preserve it) — derive it from the
    # file's own mtime so ordering by recency still works.
    return Lesson(
        id=data["id"],
        name=data["name"],
        rule_ids=data["rule_ids"],
        scenario_id=data.get("scenario_id"),
        created_at=datetime.fromtimestamp(path.stat().st_mtime, tz=UTC),
    )
