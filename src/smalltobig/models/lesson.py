"""Lesson: 1-3 accepted rules sequenced together, plus (from Phase 5
onward) one roleplay scenario. See docs/PLAN.md §2 Stage 4.

`scenario_id` stays None until Phase 5 builds scenarios — no phase
depends on a later one (docs/PLAN.md §5). Unlike Rule, a Lesson has no
accept/reject workflow: PLAN.md's Stage 4 says lessons are "generated by
the model... then hand-edited" directly, so there's no state machine to
track — see store/repo_lessons.py for what that means for persistence.
"""

from __future__ import annotations

from datetime import datetime

from pydantic import BaseModel

from smalltobig.models.source import slugify


class Lesson(BaseModel):
    id: str
    name: str
    rule_ids: list[str]
    scenario_id: str | None = None
    created_at: datetime


def generate_lesson_id(name: str) -> str:
    return slugify(name, max_words=6)
